function getGames() {

    const saved = localStorage.getItem("akumaGames");

    if (saved) {
        return JSON.parse(saved);
    }

    localStorage.setItem(
        "akumaGames",
        JSON.stringify(defaultGames)
    );

    return defaultGames;
}


function saveGames(games) {

    localStorage.setItem(
        "akumaGames",
        JSON.stringify(games)
    );

}


function whatsappLink(game) {
    return WHATSAPP_LINK;
}


function showGames(consoleFilter = "todos") {

    const container =
        document.getElementById("gamesContainer");

    if (!container) return;

    const games = getGames();

    let filtered = games;

    if (consoleFilter !== "todos") {

        filtered = games.filter(
            game => game.console === consoleFilter
        );

    }

    container.innerHTML = "";

    filtered.forEach(game => {

        const card = document.createElement("article");

        card.className = "game-card";

        card.innerHTML = `
            <img
                class="game-image"
                src="${game.image}"
                alt="${game.name}"
                loading="lazy"
            >

            <div class="game-info">

                <h3>${game.name}</h3>

                <div class="console">
                    ${game.console}
                </div>

                <span class="status">
                    ${game.status}
                </span>

                <a
                    class="whatsapp"
                    href="${whatsappLink(game)}"
                    target="_blank"
                    rel="noopener"
                >
                    💬 CONSULTAR POR WHATSAPP
                </a>

            </div>
        `;

        container.appendChild(card);

    });

}


document.querySelectorAll(".filter").forEach(button => {

    button.addEventListener("click", () => {

        document
            .querySelectorAll(".filter")
            .forEach(btn =>
                btn.classList.remove("active")
            );

        button.classList.add("active");

        showGames(button.dataset.console);

    });

});


const themeButton =
    document.getElementById("themeButton");


if (themeButton) {

    themeButton.addEventListener("click", () => {

        document.body.classList.toggle("light");

        const light =
            document.body.classList.contains("light");

        localStorage.setItem(
            "akumaTheme",
            light ? "light" : "dark"
        );

        themeButton.textContent =
            light ? "🌙" : "☀️";

    });


    if (
        localStorage.getItem("akumaTheme")
        === "light"
    ) {

        document.body.classList.add("light");

        themeButton.textContent = "🌙";

    }

}


showGames();
